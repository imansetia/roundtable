"""Command-line entry point: ``roundtable init`` and ``roundtable run`` (M11).

The console script ``roundtable`` (pyproject [project.scripts]) runs
this module's main(). The CLI is a thin wrapper around what already
exists: init writes agents.json with generated tokens, run starts
the board exactly like ``python -m roundtable``. No tool behaviour
changes; the server's core logic is untouched.
"""

import argparse
import json
import os
import secrets
import sys
from pathlib import Path

from .server import main as run_server

# The same three agents as agents.example.json, with real tokens
# generated at init time instead of REPLACE-ME placeholders.
DEFAULT_AGENTS = [
    {"name": "planner", "role": "leader", "skills": ["planning", "review"]},
    {"name": "coder", "role": "worker", "skills": ["python"]},
    {"name": "reviewer", "role": "worker", "skills": ["review"]},
]

MCP_URL = "http://127.0.0.1:8000/mcp"


def _init(args: argparse.Namespace) -> int:
    """Generate agents.json with fresh tokens. Never overwrites an
    existing file, and never echoes the generated tokens."""
    path = Path(args.path)
    if path.exists():
        print(
            f"error: {path} already exists — refusing to overwrite it.",
            file=sys.stderr,
        )
        print(
            "Delete it (or point --path at a fresh location) and try again.",
            file=sys.stderr,
        )
        return 2
    agents = [
        {**agent, "token": secrets.token_urlsafe(48)}
        for agent in DEFAULT_AGENTS
    ]
    payload = {
        "_comment": "Generated by `roundtable init`. Never commit this file. "
        "Exactly one agent must be the leader.",
        "agents": agents,
    }
    path.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")
    os.chmod(path, 0o600)
    print(f"Board config written to {path} (mode 600).")
    print()
    print("Start it:")
    print("  roundtable run")
    print()
    print(f"MCP URL: {MCP_URL}")
    print()
    print("Connect an MCP client with:")
    print("  {")
    print('    "mcpServers": {')
    print('      "roundtable": {')
    print('        "type": "http",')
    print(f'        "url": "{MCP_URL}",')
    print(
        '        "headers": {"Authorization": "Bearer <the token for your '
        'agent in agents.json>"}'
    )
    print("      }")
    print("    }")
    print("  }")
    print()
    print("Tokens live in agents.json — never paste them into a chat.")
    return 0


def _run(args: argparse.Namespace) -> int:
    """Start the board (same defaults as ``python -m roundtable``).
    The flags only override the matching environment variables."""
    if args.host is not None:
        os.environ["ROUNDTABLE_HOST"] = args.host
    if args.port is not None:
        os.environ["ROUNDTABLE_PORT"] = str(args.port)
    if args.db_path is not None:
        os.environ["ROUNDTABLE_DB_PATH"] = args.db_path
    if args.agents_config is not None:
        os.environ["ROUNDTABLE_AGENTS_CONFIG"] = args.agents_config
    run_server()
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="roundtable",
        description="Roundtable — a shared task board for AI agents over MCP.",
    )
    sub = parser.add_subparsers(dest="command", metavar="COMMAND")
    init_parser = sub.add_parser(
        "init", help="Generate agents.json with fresh tokens"
    )
    init_parser.add_argument(
        "--path",
        default="agents.json",
        help="Where to write the config (default: agents.json)",
    )
    run_parser = sub.add_parser(
        "run", help="Start the board (same defaults as python -m roundtable)"
    )
    run_parser.add_argument("--host", default=None)
    run_parser.add_argument("--port", type=int, default=None)
    run_parser.add_argument("--db-path", default=None)
    run_parser.add_argument("--agents-config", default=None)
    args = parser.parse_args(argv)
    if args.command == "init":
        return _init(args)
    if args.command == "run":
        return _run(args)
    # Bare `roundtable` with no subcommand: print usage, do nothing.
    parser.print_usage(sys.stderr)
    return 2


if __name__ == "__main__":
    sys.exit(main())
